const originalText = new WeakMap();

function storedLanguage() {
  try { return localStorage.getItem('portfolio-language') === 'it' ? 'it' : 'en'; }
  catch (_) { return 'en'; }
}

let currentLanguage = storedLanguage();

function translateTextNodes(root, language) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const original = originalText.get(node);
    const match = original.match(/^(\s*)([\s\S]*?)(\s*)$/);
    const key = match[2];
    node.nodeValue = `${match[1]}${language === 'it' && translations[key] ? translations[key] : key}${match[3]}`;
  }
}

function updateMenuButton() {
  const button = document.querySelector('.menu-button');
  if (!button) return;
  const open = document.querySelector('.nav')?.classList.contains('open');
  button.textContent = currentLanguage === 'it' ? (open ? 'Chiudi' : 'Menu') : (open ? 'Close' : 'Menu');
  button.setAttribute('aria-label', currentLanguage === 'it' ? (open ? 'Chiudi menu' : 'Apri menu') : (open ? 'Close menu' : 'Open menu'));
}

function applyLanguage(language) {
  currentLanguage = language === 'it' ? 'it' : 'en';
  document.documentElement.lang = currentLanguage;
  translateTextNodes(document.body, currentLanguage);
  const originalTitle = document.documentElement.dataset.originalTitle || document.title;
  document.documentElement.dataset.originalTitle = originalTitle;
  document.title = currentLanguage === 'it' && translations[originalTitle] ? translations[originalTitle] : originalTitle;
  document.querySelectorAll('.language-switch button').forEach((button) => {
    const active = button.dataset.language === currentLanguage;
    button.classList.toggle('active', active);
    button.setAttribute('aria-pressed', String(active));
  });
  updateMenuButton();
  if (experienceStatus) experienceStatus.textContent = experienceStatusText(currentExperiencePage);
  try { localStorage.setItem('portfolio-language', currentLanguage); } catch (_) {}
}

function createLanguageSwitch() {
  const switcher = document.createElement('div');
  switcher.className = `language-switch${document.querySelector('.nav') ? '' : ' language-switch--case'}`;
  switcher.setAttribute('aria-label', 'Language selection');
  switcher.innerHTML = '<button type="button" data-language="en" aria-label="English">EN</button><span aria-hidden="true">/</span><button type="button" data-language="it" aria-label="Italiano">IT</button>';
  const header = document.querySelector('.nav');
  (header || document.body).appendChild(switcher);
  switcher.querySelectorAll('button').forEach((button) => button.addEventListener('click', () => applyLanguage(button.dataset.language)));
}

createLanguageSwitch();

const nav = document.querySelector('.nav');
const menuButton = document.querySelector('.menu-button');

if (nav && menuButton) {
  menuButton.addEventListener('click', () => {
    const open = nav.classList.toggle('open');
    menuButton.setAttribute('aria-expanded', String(open));
    updateMenuButton();
  });
  document.querySelectorAll('.nav nav a').forEach((link) => link.addEventListener('click', () => {
    nav.classList.remove('open');
    menuButton.setAttribute('aria-expanded', 'false');
    updateMenuButton();
  }));
}

const experienceCards = [...document.querySelectorAll('[data-experience-card]')];
const experiencePageButtons = [...document.querySelectorAll('[data-experience-page]')];
const experienceStatus = document.querySelector('.experience-pagination__status');
const projectsPerPage = 4;
let currentExperiencePage = 1;

function experienceStatusText(page) {
  const first = (page - 1) * projectsPerPage + 1;
  const last = Math.min(page * projectsPerPage, experienceCards.length);
  const english = `Projects ${first}–${last} of ${experienceCards.length}`;
  return currentLanguage === 'it' && translations[english] ? translations[english] : english;
}

function renderExperiencePage(page, moveToGrid = false) {
  if (!experienceCards.length) return;
  const pageCount = Math.ceil(experienceCards.length / projectsPerPage);
  currentExperiencePage = Math.min(Math.max(page, 1), pageCount);
  experienceCards.forEach((card, index) => {
    card.hidden = Math.floor(index / projectsPerPage) + 1 !== currentExperiencePage;
  });
  experiencePageButtons.forEach((button) => {
    const active = Number(button.dataset.experiencePage) === currentExperiencePage;
    button.classList.toggle('active', active);
    if (active) button.setAttribute('aria-current', 'page');
    else button.removeAttribute('aria-current');
  });
  document.querySelector('[data-page-direction="previous"]')?.toggleAttribute('disabled', currentExperiencePage === 1);
  document.querySelector('[data-page-direction="next"]')?.toggleAttribute('disabled', currentExperiencePage === pageCount);
  if (experienceStatus) experienceStatus.textContent = experienceStatusText(currentExperiencePage);
  if (moveToGrid) document.querySelector('.experience-grid')?.scrollIntoView({ behavior: 'smooth', block: 'start' });
}

experiencePageButtons.forEach((button) => button.addEventListener('click', () => renderExperiencePage(Number(button.dataset.experiencePage), true)));
document.querySelector('[data-page-direction="previous"]')?.addEventListener('click', () => renderExperiencePage(currentExperiencePage - 1, true));
document.querySelector('[data-page-direction="next"]')?.addEventListener('click', () => renderExperiencePage(currentExperiencePage + 1, true));

renderExperiencePage(1);

applyLanguage(currentLanguage);

