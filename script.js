function translateTextNodes(root, language) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const original = originalText.get(node);
    const match = original.match(/^(\s*)([\s\S]*?)(\s*)$/);
    const key = match[2];
    const translated = language === 'it' && activeTranslations[key] ? activeTranslations[key] : key;
    const leading = language === 'it' && /^[,.;:!?)]/.test(translated) ? '' : match[1];
    const trailing = language === 'it' && /[’']$/.test(translated) ? '' : match[3];
    node.nodeValue = `${leading}${translated}${trailing}`;
  }
}

function translateAttributes(root, language) {
  root.querySelectorAll('[aria-label], img[alt]').forEach((element) => {
    if (!originalAttributes.has(element)) originalAttributes.set(element, {});
    const stored = originalAttributes.get(element);
    ['aria-label', 'alt'].forEach((attribute) => {
      if (!element.hasAttribute(attribute)) return;
      if (!(attribute in stored)) stored[attribute] = element.getAttribute(attribute);
      const original = stored[attribute];
      element.setAttribute(attribute, language === 'it' && activeTranslations[original] ? activeTranslations[original] : original);
    });
  });
}

function translateMetadata(language) {
  document.querySelectorAll('meta[name="description"], meta[property="og:title"], meta[property="og:description"], meta[property="og:image:alt"], meta[name="twitter:title"], meta[name="twitter:description"], meta[name="twitter:image:alt"]').forEach((meta) => {
    if (!meta.dataset.originalContent) meta.dataset.originalContent = meta.content;
    const original = meta.dataset.originalContent;
    meta.content = language === 'it' && activeTranslations[original] ? activeTranslations[original] : original;
  });
}

